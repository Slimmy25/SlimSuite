local bad=0
local function check(label,ok) if not ok then bad=bad+1; print("MISMATCH "..label) end end
local meter=SlimSuiteMeter
check("talent source label",meter.SourceTags({kind="talent"})==" ["..SS.T("Talent").."]")
check("gear source label",meter.SourceTags({kind="item"})==" ["..SS.T("Gear").."]")
check("amulet source key label",meter.SourceTags({kind="effect",sourceKey="amulet:ivy:r1"})==" ["..SS.T("Gear").."]")
check("free cast origin label",meter.SourceTags({kind="ability",originSourceKeys={"talent:warlock.nightfall:r1"}})==" ["..SS.T("Talent").."]")
check("unknown origin is not invented",meter.SourceTags({kind="generic",sourceKey="other"})=="")
local p0,p1,p2=SS.LegendaryChance(0,0),SS.LegendaryChance(1,0),SS.LegendaryChance(2,0)
check("chart baseline is one percent",math.abs(p0-.01)<.000001)
check("chart 100 percent luck gives about 8.08 percent legendary",math.abs(p1-16/198)<.000001)
check("legendary odds grow nonlinearly",p2-p1>p1-p0)
check("amulets receive their separate chart bonus",SS.LegendaryChance(0,0,.5)>p0)
check("level bonus caps at thirty percent",SS.LegendaryChance(.2,30)==SS.LegendaryChance(.2,100))
check("missing live luck stays unavailable",SS.LegendaryChance(nil,20)==nil)
check("extreme luck remains bounded",SS.LegendaryChance(1e100,30)<=1)
SS.SetupEnd(true)
check("luck prototype is optional",SS.ELEMENTS.SlimSuiteLuckFrame.optional and not SS.FeatureEnabled("SlimSuiteLuckFrame"))
SS.ENV.SU.SetMode("SlimSuiteLuckFrame","enabled","Legendary luck")
AZS_STATS={luck=.3}; SS.UpdateLuck()
check("enabled luck widget displays real current luck",SlimSuiteLuckFrame:IsShown() and string.find(SlimSuiteLuckFrame.luckTag:GetText(),"30%",1,true))
check("luck display gives percentages without advisory statuses",SlimSuiteLuckFrame.bigTag:GetText()==SS.T("chance per card, right now") and SS.LuckTrend==nil)
SS.StartSetup(true); SS.RefreshEditHandles()
check("luck widget participates in green mover",SS.ENV.handles.SlimSuiteLuckFrame and SS.ENV.handles.SlimSuiteLuckFrame:IsShown())
local handle=SS.ENV.handles.SlimSuiteLuckFrame
check("luck has the shared resize grip",handle and handle.resizeGrip and handle.resizeGrip:GetScript("OnMouseDown")~=nil)
SS.DB().sizes.SlimSuiteLuckFrame={w=360,h=240}; SS.ENV.PlaceAll(); SS.UpdateLuck()
check("luck renderer respects custom dimensions",SlimSuiteLuckFrame:GetWidth()==360 and SlimSuiteLuckFrame:GetHeight()==240)
SS.SetupEnd(true)
SS.ENV.SU.SetMode("SlimSuiteLuckFrame","disabled","Legendary luck")
SS.StartSetup(true); SS.RefreshEditHandles(); SS.UpdateLuck()
check("optional luck is still green and placeable in setup",SS.ENV.handles.SlimSuiteLuckFrame:IsShown() and SlimSuiteLuckFrame:IsShown() and SlimSuiteLuckFrame:GetAlpha()==1)
SS.SetupEnd(true); SS.UpdateLuck()
check("disabled luck preview disappears outside setup",not SlimSuiteLuckFrame:IsShown())
local phase="ready"; AZS_GetPhase=function() return phase end; AZS_ZONE={run="luck-progress"}; AZS_STATS={luck=.2}
local level=10; UnitLevel=function() return level end
SS.LuckProgress(); phase="playing"; AZS_STATS.luck=.5
local grown=SS.LuckProgress()
check("progress retains actual starting and current luck",grown.baseline.luck==.2 and grown.baseline.fromStart and grown.luck==.5 and grown.gain>0)
local xmax,ymax=grown.maxLuck,grown.maxChance
AZS_STATS.luck=.2; level=11; local dropped=SS.LuckProgress()
check("normal stat or level changes do not rescale axes",dropped.maxLuck==xmax and dropped.maxChance==ymax)
check("level alone is not credited as a luck investment",math.abs(dropped.gain)<.00001)
AZS_STATS.luck=3; local expanded=SS.LuckProgress(); AZS_STATS.luck=.2; local restored=SS.LuckProgress()
check("exceptional luck expands but never shrinks plot scale",expanded.maxLuck==3 and restored.maxLuck==3 and restored.maxChance==expanded.maxChance)
AZS_STATS.luck=nil; local missing=SS.LuckProgress()
check("missing stats never become fabricated zero luck",missing.luck==nil and missing.baseline.luck==.2)
AZS_ZONE.run="joined-midrun"; AZS_STATS.luck=.7; local joined=SS.LuckProgress()
check("joining midrun does not invent a run-start baseline",joined.baseline.luck==.7 and not joined.baseline.fromStart)
print("meter/luck problems: "..bad)
assert(bad==0 and #ERRORS==0,"meter/luck regressions")
