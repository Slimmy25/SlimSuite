"""Validate complete translation dictionaries and generate Lua 5.0-safe tables."""
from pathlib import Path
import json
import re
import sys

root = Path(__file__).resolve().parents[1]
canonical = json.loads((root / 'locales/enUS.json').read_text(encoding='utf-8'))
def lua_quote(text):
    # a Lua 5.0 string literal: escapes backslash, quote and control characters
    out = []
    for ch in text:
        if ch == '\\': out.append('\\\\')
        elif ch == '"': out.append('\\"')
        elif ch == '\n': out.append('\\n')
        elif ch == '\r': out.append('\\r')
        elif ch == '\t': out.append('\\t')
        elif ord(ch) < 32: out.append('\\%03d' % ord(ch))
        else: out.append(ch)
    return '"' + ''.join(out) + '"'

# Each language is kept as Lua source text and compiled only when the client needs it (see SlimSuiteLocale.lua).
lines = ['-- Generated by tools/build-locales.py; edit locales/*.json.', 'SS.LOCALE_SOURCE = {};']

for path in sorted((root / 'locales').glob('*.json')):
    data = json.loads(path.read_text(encoding='utf-8'))
    if set(data) != set(canonical):
        raise SystemExit('Missing/extra keys in ' + path.name)
    body = ['return {']
    for key in sorted(data):
        value = data[key]
        if not isinstance(value, str) or not value.strip():
            raise SystemExit('Empty/non-string translation: ' + path.name + ': ' + key)
        pattern = r'%(?:\d+\$)?[sd]'
        if re.findall(pattern, key) != re.findall(pattern, value):
            raise SystemExit('Format placeholders differ: ' + path.name + ': ' + key)
        body.append(' [' + json.dumps(key, ensure_ascii=False) + '] = ' + json.dumps(value, ensure_ascii=False) + ',')
    body.append('};')
    lines.append('SS.LOCALE_SOURCE.' + path.stem + ' = ' + lua_quote('\n'.join(body)))
lines.append('SS.LOCALE_TEXT = setmetatable({}, { __index = function(t, code)')
lines.append(' local src = SS.LOCALE_SOURCE[code];')
lines.append(' if ( not src ) then return nil; end')
lines.append(' local compile = loadstring or load;');
lines.append(' local chunk = compile(src);')
lines.append(' local dict = (chunk and chunk()) or {};')
lines.append(' rawset(t, code, dict);')
lines.append(' return dict;')
lines.append('end });')
output = '\n'.join(lines) + '\n'
target = root / 'SlimSuite/SlimSuiteLocaleExtra.lua'
if '--check' in sys.argv:
    if target.read_text(encoding='utf-8') != output:
        raise SystemExit('Generated translation tables are out of date')
else:
    target.write_text(output, encoding='utf-8')
print('Complete dictionaries: %d keys per locale' % len(canonical))
