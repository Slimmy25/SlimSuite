"""Validate complete translation dictionaries and generate Lua 5.0-safe tables."""
from pathlib import Path
import json
import re
import sys

root = Path(__file__).resolve().parents[1]
canonical = json.loads((root / 'locales/enUS.json').read_text(encoding='utf-8'))
lines = ['-- Generated by tools/build-locales.py; edit locales/*.json.', 'SS.LOCALE_TEXT = {};']
for path in sorted((root / 'locales').glob('*.json')):
    data = json.loads(path.read_text(encoding='utf-8'))
    if set(data) != set(canonical):
        raise SystemExit('Missing/extra keys in ' + path.name)
    lines.append('SS.LOCALE_TEXT.' + path.stem + ' = {')
    for key in sorted(data):
        value = data[key]
        if not isinstance(value, str) or not value.strip():
            raise SystemExit('Empty/non-string translation: ' + path.name + ': ' + key)
        pattern = r'%(?:\d+\$)?[sd]'
        if re.findall(pattern, key) != re.findall(pattern, value):
            raise SystemExit('Format placeholders differ: ' + path.name + ': ' + key)
        lines.append(' [' + json.dumps(key, ensure_ascii=False) + '] = ' + json.dumps(value, ensure_ascii=False) + ',')
    lines.append('};')
output = '\n'.join(lines) + '\n'
target = root / 'SlimSuite/SlimSuiteLocaleExtra.lua'
if '--check' in sys.argv:
    if target.read_text(encoding='utf-8') != output:
        raise SystemExit('Generated translation tables are out of date')
else:
    target.write_text(output, encoding='utf-8')
print('Complete dictionaries: %d keys per locale' % len(canonical))
