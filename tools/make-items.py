# Writes SlimSuite/SlimSuiteItems.lua from the launcher's item list (assets/items.txt in the Azeroth Survivors
# Launcher repo): every ring, trinket and amulet by its icon. An icon that two items share gets no name (the row then
# shows the item's own name from the game), so a shared icon never shows the wrong item.
# Run after a game update:  python3 tools/make-items.py <path to the launcher>/assets/items.txt
import sys, os
src = sys.argv[1]
section, items = None, []
for line in open(src, encoding='utf-8'):
    line = line.rstrip('\r\n')
    if line.startswith('@'):
        section = line.split()[0][1:]
        continue
    if section in ('jewelry', 'amulet') and line.strip():
        f = [p.strip() for p in line.split('|')]
        if len(f) >= 3 and f[2]:
            items.append((f[2], f[1]))
names = {}
for icon, name in items:
    names.setdefault(icon, []).append(name)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'SlimSuite', 'SlimSuiteItems.lua')
with open(out, 'w', encoding='utf-8', newline='\r\n') as f:
    f.write('-- Azeroth Survivors jewelry icon catalog: rings, trinkets and amulets by icon. Generated by tools/make-items.py\n')
    f.write('-- from the launcher\'s assets/items.txt; do not edit by hand. Only used for a name when the game cannot give one.\n')
    f.write('SlimSuiteItemCatalog = {\n')
    for icon, n in names.items():
        if len(n) == 1:
            f.write('    ["%s"] = "%s",\n' % (icon, n[0].replace('\\', '\\\\').replace('"', '\\"')))
        else:
            f.write('    -- %s is shared by %s: no name\n' % (icon, ', '.join(n)))
    f.write('}\n')
print('%d items, %d icons written to %s' % (len(items), len(names), out))
